const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkgDir = path.join(root, 'crates', 'mixer-wasm', 'pkg');
const srcDir = path.join(root, 'frontend', 'src', 'worklet');
const webDir = path.join(root, 'web');

// Read glue
let glue = fs.readFileSync(path.join(pkgDir, 'mixer_wasm.js'), 'utf-8');

// Guard: a node-target pkg (e.g. left behind by `make test-wasm`) inlines
// require('fs') to load the wasm — that throws in AudioWorkletGlobalScope,
// so registerProcessor never runs and the page dies with
// "mixer-processor is not defined". Require `make build-web` first.
if (/require\(/.test(glue)) {
    console.error('ERROR: crates/mixer-wasm/pkg/mixer_wasm.js is a node-target build (contains require()).');
    console.error('       Run `make build-web` to regenerate the web-target pkg before building the worklet.');
    process.exit(1);
}

// Strip ES module syntax
glue = glue.replace(/^export\s+/gm, '');
glue = glue.replace(/^export\s*\{[^}]+\};?\s*$/gm, '');
glue = glue.replace(/^\{\s*initSync[\s\S]*?\};\s*$/gm, '');
glue = glue.replace(/^\{\s*\w+\s+as\s+\w+\s*\};?\s*$/gm, '');
glue = glue.replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, '');
glue = glue.replace(/module_or_path\s*=\s*new URL\([^)]+\);/m,
    "module_or_path = undefined; // stripped for worklet");
glue = glue.replace(/^exports\.\w+\s*=\s*\w+;?\s*$/gm, '');
glue = glue.replace(/^module\.exports\s*=\s*\{[\s\S]*?\};?\s*$/gm, '');
glue = glue.replace(/^const\s+\w+\s*=\s*require\([^)]+\);?\s*$/gm, '');

const polyfill = fs.readFileSync(path.join(srcDir, 'text-encoder-decoder-polyfill.js'), 'utf-8');
const processor = fs.readFileSync(path.join(srcDir, 'worklet-template.js'), 'utf-8');

const output = '// AUTO-GENERATED by build-worklet.js\n' +
    '// Polyfills\n' + polyfill + '\n' +
    '// wasm-bindgen glue\n' + glue + '\n' +
    '// Processor\n' + processor;

fs.writeFileSync(path.join(webDir, 'mixer-worklet-processor.js'), output);
console.log('Built mixer-worklet-processor.js (' + output.length + ' bytes)');
