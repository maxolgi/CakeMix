const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkgDir = path.join(root, 'crates', 'mixer-wasm', 'pkg');
const webDir = path.join(root, 'web');

// Read glue
let glue = fs.readFileSync(path.join(pkgDir, 'mixer_wasm.js'), 'utf-8');

// Strip ES module syntax
glue = glue.replace(/^export\s+/gm, '');
glue = glue.replace(/^export\s*\{[^}]+\};?\s*$/gm, '');
glue = glue.replace(/^\{\s*initSync[\s\S]*?\};\s*$/gm, '');
glue = glue.replace(/module_or_path\s*=\s*new URL\([^)]+\);/m,
    "module_or_path = undefined; // stripped for worklet");

const polyfill = fs.readFileSync(path.join(webDir, 'text-encoder-decoder-polyfill.js'), 'utf-8');
const processor = fs.readFileSync(path.join(webDir, 'worklet-template.js'), 'utf-8');

const output = '// AUTO-GENERATED by build-worklet.js\n' +
    '// Polyfills\n' + polyfill + '\n' +
    '// wasm-bindgen glue\n' + glue + '\n' +
    '// Processor\n' + processor;

fs.writeFileSync(path.join(webDir, 'mixer-worklet-processor.js'), output);
console.log('Built mixer-worklet-processor.js (' + output.length + ' bytes)');
